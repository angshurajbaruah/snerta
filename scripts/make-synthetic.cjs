#!/usr/bin/env node
/**
 * Generates the synthetic sessions in docs/synthetic/. See that folder's README.
 *
 * These are NOT data. They exist so the Pro Max viewport (430x932) and the left-handed
 * rail — neither of which any real session covers — can be exercised by the analysis
 * code and the app. Shaped from the published reach literature, not from a person.
 */
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, '..', 'docs', 'synthetic');

let seed = 20261114;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
const jit = (base, pct) => Math.round(base * (1 + (rnd() - 0.5) * 2 * pct));

const COLS = [0.12, 0.5, 0.88];
const ROWS = [0.06, 0.28, 0.5, 0.72, 0.94];
/** Left-handed on a tall screen: far diagonal is top-right; top and bottom rows cost more. */
const zoneBase = (c, r) => 470 + (r === 0 ? 520 : r === 1 ? 210 : r === 3 ? 90 : r === 4 ? 250 : 0) + (c === 2 ? 380 : c === 1 ? 90 : 0);

function makeSession(hand, label) {
  const samples = [];
  let t = Date.parse('2026-11-14T13:00:00Z');
  for (let pass = 0; pass < 2; pass++) {
    for (const id of [...Array(15).keys()].sort(() => rnd() - 0.5)) {
      const c = id % 3, r = Math.floor(id / 3);
      const lat = jit(zoneBase(c, r), 0.18);
      t += lat + 260;
      samples.push({
        index: samples.length, targetId: id, pointerType: 'touch',
        targetX: COLS[c], targetY: ROWS[r],
        pointerX: +(COLS[c] + (rnd() - 0.5) * 0.05).toFixed(4),
        pointerY: +(ROWS[r] + (rnd() - 0.5) * 0.03).toFixed(4),
        latencyMs: lat, promptRestarted: false,
        viewportW: 430, viewportH: 932, panelW: 430, panelH: 868,
        occurredAtIso: new Date(t).toISOString(),
      });
    }
  }
  const byZone = [...Array(15)].map((_, id) => {
    const v = samples.filter((s) => s.targetId === id).map((s) => s.latencyMs).sort((a, b) => a - b);
    return (v[0] + v[1]) / 2;
  });
  const labels = [...Array(15)].map((_, id) => {
    const c = id % 3, r = Math.floor(id / 3);
    if (r === 0 && c === 2) return 'hard';
    if (r === 0) return 'stretch';
    if ((r === 1 || r === 4) && c === 2) return 'stretch';
    return 'easy';
  });
  // ABBA with discovery cost on snerta's first run, as every real session showed (D88).
  const trials = [
    { mode: 'kab', position: 1, targetId: 'm2', durationMs: jit(14200, 0.08), comfort: 4, offTaskTaps: 2, completed: true },
    { mode: 'standard', position: 2, targetId: 'm5', durationMs: jit(11800, 0.08), comfort: 3, offTaskTaps: 0, completed: true },
    { mode: 'standard', position: 3, targetId: 'm7', durationMs: jit(9900, 0.08), comfort: 3, offTaskTaps: 0, completed: true },
    { mode: 'kab', position: 4, targetId: 'm9', durationMs: jit(8100, 0.08), comfort: 5, offTaskTaps: 0, completed: true },
  ];
  const med = (a) => { const s = [...a].sort((x, y) => x - y); return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2; };
  const sum = (m) => {
    const r = trials.filter((x) => x.mode === m), d = r.map((x) => x.durationMs);
    return { durationMs: med(d), comfort: r.reduce((a, x) => a + x.comfort, 0) / r.length, spread: Math.max(...d) - Math.min(...d) };
  };
  const k = sum('kab'), s = sum('standard');
  const within = Math.max(k.spread, s.spread), delta = k.durationMs - s.durationMs;
  return {
    SYNTHETIC: 'THIS FILE IS NOT A REAL SESSION. Generated by scripts/make-synthetic.cjs to exercise the Pro Max viewport (430x932) and the left-handed rail, which no real session covers. It is NOT evidence and must never be pooled, quoted or charted as a result.',
    synthetic: true, syntheticReason: label,
    schemaVersion: 'snerta-0.3', build: 'milestone-5-abba',
    exportedAtIso: new Date(t + 90000).toISOString(),
    hand, evidence: 'touch', calibrationSkipped: false, sampleCount: 30, samples,
    nonTargetObservations: [], pageHiddenCount: 0,
    selfReport: labels.map((label, zoneId) => ({ zoneId, label })), gripChanged: 'no',
    latencyByZoneMs: byZone, trials, firstMode: 'kab',
    comparison: {
      durationDeltaMs: delta, comfortDelta: +(k.comfort - s.comfort).toFixed(1), balanced: true,
      withinSpreadMs: within, insideNoise: Math.abs(delta) < within, completedCount: 4,
      standard: { durationMs: s.durationMs, comfort: s.comfort, meanPosition: 2.5 },
      kab: { durationMs: k.durationMs, comfort: k.comfort, meanPosition: 2.5 },
    },
    preference: 'kab',
    limitations: ['SYNTHETIC DATA. No person produced this. It exists to test code paths, not to support any claim.'],
  };
}

for (const [tag, label] of [
  ['small-hand', 'Left-handed, Pro Max 430x932, small thumb'],
  ['medium-hand', 'Left-handed, Pro Max 430x932, medium thumb'],
]) {
  const f = path.join(OUT, `SYNTHETIC-promax-left-${tag}.json`);
  fs.writeFileSync(f, JSON.stringify(makeSession('left', label), null, 2));
  console.log('wrote', path.relative(process.cwd(), f));
}
